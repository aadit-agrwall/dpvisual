def _blk(pos, s=(1.4, 1.0, 0.6)):
    m = Prism(dimensions=list(s))
    m.set_fill("#FFFFFF", 1); m.set_stroke("#000000", 2)
    m.move_to(np.array(pos, dtype=float))
    return m


def _sph(r, nlat=7, nlon=10):
    out = []
    for i in range(1, nlat):
        th = np.pi * i / nlat
        for j in range(nlon):
            a, b = 2 * np.pi * j / nlon, 2 * np.pi * (j + 1) / nlon
            out.append(segment(np.array([r * np.sin(th) * np.cos(a), r * np.sin(th) * np.sin(a), r * np.cos(th)]),
                               np.array([r * np.sin(th) * np.cos(b), r * np.sin(th) * np.sin(b), r * np.cos(th)]), width=2))
    for j in range(nlon):
        a = 2 * np.pi * j / nlon
        for i in range(nlat):
            t1, t2 = np.pi * i / nlat, np.pi * (i + 1) / nlat
            out.append(segment(np.array([r * np.sin(t1) * np.cos(a), r * np.sin(t1) * np.sin(a), r * np.cos(t1)]),
                               np.array([r * np.sin(t2) * np.cos(a), r * np.sin(t2) * np.sin(a), r * np.cos(t2)]), width=2))
    return out


def _on_sph(r, th, ph):
    return np.array([r * np.sin(th) * np.cos(ph), r * np.sin(th) * np.sin(ph), r * np.cos(th)])


class Page157(Page146):

    def construct(self):
        self.setup_stage("oblique", ZOOM)
        self._v = "oblique"; self._sub = None; self._eq = None
        self.s_dep(); self.wipe()
        self.s_period(); self.wipe()
        self.s_factors(); self.wipe()
        self.s_gain(); self.wipe()
        self.s_manifold(); self.wipe()
        self.s_walk(); self.wipe()
        self.wait(0.4)

    # ---- 1. dependencies between regions ----
    def s_dep(self):
        self.caption(r"Dependencies between regions allow nonlocal generalization")
        self.say(r"Additional assumptions about the data-generating distribution")
        self.go("oblique"); self.floor(-0.3)
        xs = [-3.0 + i * 1.2 for i in range(6)]
        tiles = [_blk((x, 0.0, 0.05), (0.95, 1.4, 0.1)) for x in xs]
        lag = 0.08
        self.act("stagger", LaggedStart(*[FadeIn(t) for t in tiles], lag_ratio=lag),
                 run=1.2, n=len(tiles), lag=lag, at=0.0)
        self.keep(*tiles)
        links = [segment(np.array([a, 0.0, 0.5]), np.array([b, 0.0, 0.5]), width=5) for a, b in zip(xs[:-1], xs[1:])]
        self.act("cut", *[Create(l) for l in links], run=0.9)
        self.keep(*links)
        self.say(r"We can actually generalize nonlocally")
        ring = Dot3D(np.array([xs[0], 0.0, 0.4]), radius=0.15, color=ACCENT)
        self.act("pop", FadeIn(ring), run=0.5)
        self.keep(ring)
        self.act("zap", ring.animate.move_to(np.array([xs[5], 0.0, 0.4])), tiles[5].animate.set_fill(ACCENT, 0.8), run=1.0)
        self.orbit(0.35, run=1.6)

    # ---- 2. periodic assumption ----
    def s_period(self):
        self.caption(r"A strong, task-specific assumption: the function is periodic")
        self.say(r"This easily solves the checkerboard task")
        self.go("oblique"); self.floor(-0.1)
        n, step = 8, 0.62
        cells, cen = [], []
        for i in range(n):
            for j in range(n):
                p = np.array([(i - 3.5) * step, (j - 3.5) * step])
                c = _blk((p[0], p[1], 0.05), (0.58, 0.58, 0.1))
                if (i + j) % 2 == 0:
                    c.set_fill("#222222", 1)
                cells.append(c); cen.append(p)
        lag = 0.01
        self.act("stagger", LaggedStart(*[FadeIn(c) for c in cells], lag_ratio=lag),
                 run=1.4, n=len(cells), lag=lag, at=0.0)
        self.keep(*cells)
        self.say(r"One repeating unit explains the whole board")
        for (bi, bj) in [(0, 0), (2, 0), (4, 0), (6, 0)]:
            blk = [cells[(bi + a) * n + (bj + b)] for a in (0, 1) for b in (0, 1)]
            self.act("zap", *[c.animate.set_stroke(ACCENT, 6) for c in blk], run=0.4)
        self.say(r"But neural networks usually avoid such strong assumptions")
        self.orbit(0.5, run=2.0)

    # ---- 3. composition of factors ----
    def s_factors(self):
        self.caption(r"Core idea: data generated by a composition of factors")
        self.say(r"Features at multiple levels in a hierarchy")
        self.go("oblique"); self.floor(-1.4)
        lv0 = [(-3.0 + i * 2.0, 0.0, -1.0) for i in range(4)]
        lv1 = [(-2.0, 0.0, 0.3), (2.0, 0.0, 0.3)]
        lv2 = [(0.0, 0.0, 1.6)]
        levels = [lv0, lv1, lv2]
        blocks = [[_blk(p, (0.8, 0.8, 0.5)) for p in lv] for lv in levels]
        for lv in blocks:
            self.act("pop", *[FadeIn(b) for b in lv], run=0.6)
            self.keep(*lv)
        edges = [(lv0[0], lv1[0]), (lv0[1], lv1[0]), (lv0[2], lv1[1]), (lv0[3], lv1[1]),
                 (lv1[0], lv2[0]), (lv1[1], lv2[0])]
        segs = [segment(np.array(a, dtype=float), np.array(b, dtype=float), width=3) for a, b in edges]
        self.act("cut", *[Create(s) for s in segs], run=0.9)
        self.keep(*segs)
        for lv in blocks:
            self.act("zap", *[b.animate.set_fill(ACCENT, 0.9) for b in lv], run=0.5)
        self.orbit(0.35, run=1.6)

    # ---- 4. exponential gain ----
    def s_gain(self):
        self.caption(r"Mild assumptions give an exponential gain")
        self.say(r"Examples versus the number of regions that can be distinguished")
        self.go("oblique"); self.floor(-0.8)
        dots = [Dot3D(np.array([-3.4, y, 0.2]), radius=0.14, color=ACCENT) for y in (-1.0, 0.0, 1.0)]
        self.act("pop", *[FadeIn(d) for d in dots], run=0.6)
        self.keep(*dots)
        small = [_blk((-1.6 + i * 0.5, 0.0, 0.05), (0.4, 0.4, 0.1)) for i in range(3)]
        self.act("pop", *[FadeIn(s) for s in small], run=0.6)
        self.keep(*small)
        self.say(r"Deep distributed representations counter the curse of dimensionality")
        big = [_blk((0.2 + i * 0.5, -1.2 + j * 0.5, 0.05), (0.4, 0.4, 0.1)) for i in range(6) for j in range(5)]
        lag = 0.02
        self.act("stagger", LaggedStart(*[FadeIn(b) for b in big], lag_ratio=lag),
                 run=1.4, n=len(big), lag=lag, at=0.0)
        self.keep(*big)
        self.act("zap", *[b.animate.set_fill(ACCENT, 0.5) for b in big], run=0.7)
        self.orbit(0.35, run=1.6)

    # ---- 5. manifold: locally Euclidean ----
    def s_manifold(self):
        self.caption(r"5.11.3 Manifold learning")
        self.say(r"A manifold is a connected region with a neighborhood around each point")
        self.go("oblique"); self.floor(-2.7)
        r = 2.3
        wire = _sph(r)
        lag = 0.004
        self.act("stagger", LaggedStart(*[FadeIn(w) for w in wire], lag_ratio=lag),
                 run=1.4, n=len(wire), lag=lag, at=0.0)
        self.keep(*wire)
        self.say(r"From any point it locally appears to be a Euclidean space")
        p = _on_sph(r, np.pi / 3, 0.6)
        patch = _blk(p, (1.2, 1.2, 0.05))
        patch.set_fill(ACCENT, 0.5)
        dot = Dot3D(p, radius=0.14, color=ACCENT)
        self.act("pop", FadeIn(patch), FadeIn(dot), run=0.7)
        self.keep(patch, dot)
        self.say(r"The world looks like a 2-D plane but is a spherical manifold in 3-D")
        self.orbit(0.5, run=2.0)

    # ---- 6. walk on the manifold ----
    def s_walk(self):
        self.caption(r"Transformations move us on the manifold")
        self.say(r"One can walk north, south, east, or west")
        self.go("oblique"); self.floor(-2.7)
        r = 2.3
        wire = _sph(r)
        lag = 0.004
        self.act("stagger", LaggedStart(*[FadeIn(w) for w in wire], lag_ratio=lag),
                 run=1.2, n=len(wire), lag=lag, at=0.0)
        self.keep(*wire)
        pts = [(np.pi / 2, 0.6), (np.pi / 2.6, 0.6), (np.pi / 2.6, 1.2), (np.pi / 1.8, 1.2), (np.pi / 1.8, 0.6)]
        dot = Dot3D(_on_sph(r, *pts[0]), radius=0.15, color=ACCENT)
        self.act("pop", FadeIn(dot), run=0.5)
        self.keep(dot)
        for (a, b) in pts[1:]:
            q = _on_sph(r, a, b)
            self.act("cut", dot.animate.move_to(q), run=0.6)
        self.say(r"A connected set approximated by only a few degrees of freedom")
        self.orbit(0.5, run=2.0)


def main():
    os.chdir(ROOT)
    res = {"preview": "540,540", "reel": "1080,1080", "youtube": "2560,1440", "sq1440": "1440,1440"}.get(os.environ.get("P157_MODE", "reel"), "1080,1080")
    name = "Page157_" + res.replace(",", "x")
    tl = ROOT / "media/sfx/Page157_timeline.json"
    wav = ROOT / "media/sfx/Page157.wav"
    out_dir = ROOT / "assets/user-data/output"
    for p in (tl.parent, out_dir):
        p.mkdir(parents=True, exist_ok=True)
    if tl.exists():
        tl.unlink()
    env = dict(os.environ, SFX_TIMELINE=str(tl), PYTHONPATH=str(ROOT))
    log = pathlib.Path("/tmp/page_157.log")
    print(f"rendering {res} @30fps ...")
    with open(log, "w") as lf:
        rc = subprocess.run([sys.executable, "-m", "manim", "-r", res, "--fps", "30", "-o", name,
                             str(pathlib.Path(__file__).resolve()), "Page157"],
                            env=env, stdout=lf, stderr=subprocess.STDOUT).returncode
    if rc != 0 or not tl.exists():
        print("RENDER FAILED. last lines of", log)
        print("".join(log.read_text().splitlines(True)[-25:]))
        sys.exit(1)
    vids = [v for v in (ROOT / "media/videos").rglob(name + ".mp4") if "partial_movie_files" not in v.parts]
    vid = sorted(vids, key=lambda p: p.stat().st_mtime)[-1]
    data = json.load(open(tl))
    buf, slog = build_audio(data)
    write_wav(buf, wav)
    final = out_dir / (name + "_sfx.mp4")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(vid), "-i", str(wav), "-map", "0:v",
                    "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest",
                    "-movflags", "+faststart", str(final)], check=True)
    sheet = out_dir / (name + "_sheet.png")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(final), "-vf",
                    "fps=1/4,scale=360:-1,tile=4x4", "-frames:v", "1", str(sheet)])
    skipped = sum(1 for e in data["events"] if "Camera" in e["kinds"] and not e["vis"])
    print("=== SFX REPORT ===")
    print(f"timeline {data['total']:.2f}s | {len(data['events'])} plays | {len(data['cues'])} cues | {len(slog)} sounds")
    print("sounds:", dict(Counter(n for _, n in slog)))
    print(f"camera moves with an empty stage (silenced): {skipped}")
    try:
        vd = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                      "-of", "csv=p=0", str(vid)], text=True).strip()
        print(f"video duration {vd}s vs timeline {data['total']:.2f}s (should match within ~0.1s)")
    except Exception:
        pass
    print("SAVED:", final)
    print("CHECK SHEET:", sheet)
    if not os.environ.get("NOOPEN"): subprocess.run(["open", str(final)])
    if not os.environ.get("NOOPEN"): subprocess.run(["open", str(sheet)])


if __name__ == "__main__":
    main()
